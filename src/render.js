// Turns a page definition plus the content into one complete HTML document.

import { escape } from "./html.js";
import { sections } from "./sections.js";
import { linksFor } from "./select.js";
import { PAGES, SECRET_PAGE, SECTION_TITLES } from "./pages.js";

const FONTS = "https://fonts.googleapis.com/css2?family=JetBrains+Mono:wght@500;700;800&family=Montserrat:wght@500;600;700;800&family=Raleway:wght@400;500;600;700&display=swap";

function nav(current) {
  const items = PAGES.map((page) => {
    const state = page.key === current ? ' aria-current="page"' : "";
    return `<li><a href="${page.file}"${state}>${escape(page.nav)}</a></li>`;
  }).join("\n        ");
  return `<nav class="focus" aria-label="Choose a focus">
      <ul>
        ${items}
      </ul>
    </nav>`;
}

function sectionHtml(id, body) {
  return `
    <section id="${id}">
      <h2>${escape(SECTION_TITLES[id])}</h2>
      ${body}
    </section>`;
}

export function renderPage(page, content) {
  const isSecret = page.key === SECRET_PAGE.key;
  const body = page.sections
    .map((id) => ({ id, html: sections[id](content, page.key) }))
    .filter(({ html }) => html.trim() !== "")
    .map(({ id, html }) => sectionHtml(id, html))
    .join("\n");

  const links = linksFor(content.site.links, page.key)
    .map((link) => `<li><a href="${escape(link.url)}">${escape(link.label)}</a></li>`)
    .join("\n        ");

  const hint = page.key === "all"
    ? "Each focus is its own page, with only that side of me on it."
    : `This page shows only one side of me. <a href="index.html">See everything</a>.`;

  const bodyData = isSecret
    ? ""
    : ` data-secret-word="${escape(content.site.secret.word)}" data-secret-href="${escape(content.site.secret.page)}"`;

  const footerExtra = isSecret
    ? `<a class="paw" href="index.html">Back to the main page</a>`
    : `<a class="paw" href="${escape(content.site.secret.page)}" aria-label="Show the cat album">=^.^=</a>`;

  return `<!DOCTYPE html>
<html lang="en" data-mode="${page.key}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escape(page.title)}</title>
<meta name="description" content="${escape(page.lede)}">

<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="${FONTS}" rel="stylesheet">

<link rel="stylesheet" href="css/tokens.css">
<link rel="stylesheet" href="css/base.css">
<link rel="stylesheet" href="css/layout.css">
<link rel="stylesheet" href="css/components.css">
</head>
<body${bodyData}>
<!-- GENERATED by build.js. Edit the files in content/ and src/, then run: node build.js -->
<div class="wrap">

  <header>
    <h1>${escape(page.prefix)} <span class="role">${escape(page.role)}</span></h1>
    <p class="lede">${escape(page.lede)}</p>
    ${isSecret ? "" : nav(page.key)}
    <p class="hint">${hint}</p>
    <ul class="links">
        ${links}
    </ul>
  </header>

  <main>
${body}
  </main>

  <footer>
    <p>${escape(content.site.location)}. Say hello at <a href="mailto:${escape(content.site.email)}">${escape(content.site.email)}</a>.</p>
    ${footerExtra}
  </footer>

</div>
${isSecret ? "" : '<script type="module" src="js/easter-egg.js"></script>\n'}</body>
</html>
`;
}
